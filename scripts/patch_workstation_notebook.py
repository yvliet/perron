        "    print(f'Attempting to initialize Gemma 4 causal model...')\n",
        "    try:\n",
        "        model = AutoModelForCausalLM.from_pretrained(\n",
        "            str(model_dir),\n",
        "            torch_dtype=torch.float16 if torch.cuda.is_available() else torch.bfloat16,\n",
