#!/usr/bin/env python3
"""
viz_engine.py - Scientific visualization engine for Perron evaluation benchmarks.
Generates publication plots using Okabe-Ito colorblind-safe palettes,
TrueType Type 42 vector font embedding, and companion LaTeX snippets.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Union

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import gaussian_kde

# Okabe-Ito colorblind-safe palette (Wong 2011 Nature Methods)
OKABE_ITO = [
    "#0072B2",  # Blue
    "#D55E00",  # Vermilion
    "#009E73",  # Bluish green
    "#F0E442",  # Yellow
    "#56B4E9",  # Sky blue
    "#E69F00",  # Orange
    "#CC79A7",  # Reddish purple
    "#000000",  # Black
]


def apply_publication_theme(venue: str = "neurips") -> None:
    """Configures matplotlib with publication-grade typographic defaults."""
    if venue.lower() in ["ieee", "acm", "nature"]:
        fig_width = 3.35
    else:
        fig_width = 5.5

    fig_height = fig_width / 1.55

    plt.rcParams.update({
        "figure.figsize": (fig_width, fig_height),
        "figure.dpi": 300,
        "font.family": "serif",
        "font.size": 8.5,
        "axes.labelsize": 9.5,
        "axes.titlesize": 10.0,
        "xtick.labelsize": 8.0,
        "ytick.labelsize": 8.0,
        "legend.fontsize": 8.0,
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.spines.left": True,
        "axes.spines.bottom": True,
        "axes.grid": True,
        "grid.alpha": 0.15,
        "grid.linestyle": "--",
        "grid.color": "#999999",
        "lines.linewidth": 1.5,
        "lines.markersize": 5,
    })


def export_latex_figure_snippet(
    pdf_path: str,
    label: str = "fig:results",
    caption: str = "Distribution comparison across evaluation conditions.",
    output_dir: str = ".",
) -> None:
    """Generates a companion LaTeX figure environment file."""
    rel_path = os.path.basename(pdf_path)
    snippet = f"""% Companion LaTeX figure block generated by viz_engine.py
\\begin{{figure}}[t]
\\centering
\\includegraphics[width=0.98\\linewidth]{{{rel_path}}}
\\caption{{{caption}}}
\\label{{{label}}}
\\end{{figure}}
"""
    snippet_path = os.path.join(output_dir, os.path.splitext(rel_path)[0] + "_fig.tex")
    with open(snippet_path, "w", encoding="utf-8") as f:
        f.write(snippet)


def plot_raincloud(
    data_dict: Dict[str, Sequence[float]],
    title: str = "Distribution Comparison",
    xlabel: str = "Condition",
    ylabel: str = "Metric",
    output_path: str = "raincloud.pdf",
    venue: str = "neurips",
) -> None:
    """Renders a Raincloud plot (half-density KDE + boxplot + jittered raw scatter)."""
    apply_publication_theme(venue)
    fig, ax = plt.subplots()

    labels = list(data_dict.keys())
    n_groups = len(labels)
    colors = OKABE_ITO[:n_groups]
    rng = np.random.default_rng(42)

    for idx, (label, raw_vals) in enumerate(data_dict.items()):
        vals = np.asarray(raw_vals, dtype=float)
        vals = vals[~np.isnan(vals)]
        if len(vals) < 2:
            continue

        base_pos = idx

        # Half-density KDE cloud
        kde = gaussian_kde(vals)
        eval_points = np.linspace(np.min(vals), np.max(vals), 100)
        density = kde(eval_points)
        density = (density / np.max(density)) * 0.35
        ax.fill_betweenx(
            eval_points,
            base_pos,
            base_pos + density,
            color=colors[idx],
            alpha=0.45,
            edgecolor=colors[idx],
            linewidth=1,
        )

        # Narrow boxplot
        ax.boxplot(
            vals,
            positions=[base_pos],
            widths=0.10,
            orientation="vertical",
            patch_artist=True,
            showfliers=False,
            boxprops=dict(facecolor="white", edgecolor=colors[idx], linewidth=1.2),
            medianprops=dict(color="#000000", linewidth=1.5),
            whiskerprops=dict(color=colors[idx], linewidth=1.2),
            capprops=dict(color=colors[idx], linewidth=1.2),
        )

        # Jittered raw scatter
        jitter = rng.uniform(-0.25, -0.05, size=len(vals))
        ax.scatter(
            base_pos + jitter,
            vals,
            color=colors[idx],
            alpha=0.65,
            s=12,
            edgecolors="none",
            rasterized=True,
        )

    ax.set_xticks(range(n_groups))
    ax.set_xticklabels(labels, fontweight="medium")
    ax.set_title(title, pad=10)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)

    plt.tight_layout(pad=1.2)
    plt.savefig(output_path, dpi=300)
    png_path = os.path.splitext(output_path)[0] + ".png"
    plt.savefig(png_path, dpi=300)
    plt.close()

    export_latex_figure_snippet(output_path, output_dir=os.path.dirname(output_path) or ".")


def plot_performance_profile(
    algo_scores: Dict[str, Sequence[float]],
    threshold_range: Optional[Tuple[float, float]] = None,
    xlabel: str = "Normalized Score (Tau)",
    ylabel: str = "Fraction of Tasks (P(Score >= Tau))",
    output_path: str = "perf_profile.pdf",
    venue: str = "neurips",
) -> None:
    """Renders Dolan-More style performance profiles across evaluation tasks."""
    apply_publication_theme(venue)
    fig, ax = plt.subplots()

    all_scores = np.concatenate([np.asarray(s).flatten() for s in algo_scores.values()])
    if threshold_range is None:
        taus = np.linspace(np.min(all_scores), np.max(all_scores), 200)
    else:
        taus = np.linspace(threshold_range[0], threshold_range[1], 200)

    for idx, (algo_name, scores) in enumerate(algo_scores.items()):
        scores_arr = np.asarray(scores, dtype=float)
        fractions = np.mean(scores_arr[:, None] >= taus[None, :], axis=0)
        color = OKABE_ITO[idx % len(OKABE_ITO)]
        line_style = ["-", "--", "-.", ":"][idx % 4]
        ax.plot(taus, fractions, label=algo_name, color=color, linestyle=line_style, linewidth=1.8)

    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_ylim(-0.02, 1.02)
    ax.set_title("Benchmark Performance Profile", pad=10)
    ax.legend(frameon=False, loc="best")

    plt.tight_layout(pad=1.2)
    plt.savefig(output_path, dpi=300)
    png_path = os.path.splitext(output_path)[0] + ".png"
    plt.savefig(png_path, dpi=300)
    plt.close()

    export_latex_figure_snippet(
        output_path,
        label="fig:perf_profile",
        caption="Benchmark performance profiles across evaluation tasks.",
        output_dir=os.path.dirname(output_path) or ".",
    )
