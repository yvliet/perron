#!/usr/bin/env python3
"""Render paper/metrics_macros.tex from paper/claims_spec.json.

Every macro resolves to a numeric leaf of a file under results/ through an
RFC 6901 JSON Pointer. This script holds formatting rules only; it contains no
metric values. render_claims() is reused by scripts/check_facts.py.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List

REPO_ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = REPO_ROOT / "paper" / "claims_spec.json"
OUT_PATH = REPO_ROOT / "paper" / "metrics_macros.tex"
HEADER = "% Generated by scripts/generate_paper_macros.py from paper/claims_spec.json. Do not edit."


def resolve_pointer(doc: Any, pointer: str) -> Any:
    """Resolve an RFC 6901 JSON Pointer without third-party dependencies."""
    if pointer == "":
        return doc
    if not pointer.startswith("/"):
        raise ValueError(f"JSON Pointer must start with '/': {pointer!r}")
    node = doc
    for raw in pointer[1:].split("/"):
        token = raw.replace("~1", "/").replace("~0", "~")
        node = node[int(token)] if isinstance(node, list) else node[token]
    return node


def _apa(v: float) -> str:
    return "< .001" if v < 0.001 else f"= {v:.3f}"


def _cell(v: float) -> str:
    return "$<$.001" if v < 0.001 else f"{v:.3f}"


FORMATS = {
    "pct1": lambda v, n: f"{100.0 * v:.1f}\\%",
    "pct1c": lambda v, n: f"{100.0 * (1.0 - v):.1f}\\%",
    "pct1_raw": lambda v, n: f"{v:.1f}\\%",
    "pct2_raw": lambda v, n: f"{v:.2f}\\%",
    "pct_kn": lambda v, n: f"{100.0 * v / n:.1f}\\%",
    "frac": lambda v, n: f"{int(round(v * n))}/{int(n)}",
    "kn": lambda v, n: f"{int(v)}/{int(n)}",
    "int": lambda v, n: str(int(v)),
    "num1": lambda v, n: f"{v:.1f}",
    "num2": lambda v, n: f"{v:.2f}",
    "num3": lambda v, n: f"{v:.3f}",
    "num4": lambda v, n: f"{v:.4f}",
    "thousands": lambda v, n: f"{int(v):,}".replace(",", "{,}"),
    "delta_pp": lambda v, n: f"+{v:.2f}" if v > 0 else f"{v:.2f}",
    "ratio_x": lambda v, n: f"\\ensuremath{{{v:.2f}\\times}}",
    "pval": lambda v, n: _apa(v),
    "pval2": lambda v, n: f"= {v:.2f}",
    "pval3": lambda v, n: f"= {v:.3f}",
    "pval4": lambda v, n: f"= {v:.4f}",
    "pcell": lambda v, n: _cell(v),
    "gib2": lambda v, n: f"{v:.2f}~GiB",
    "mb1": lambda v, n: f"{v:.1f}~MB",
    "mb2": lambda v, n: f"{v:.2f}~MB",
    "ms1": lambda v, n: f"{v:.1f}~ms",
    "ms2": lambda v, n: f"{v:.2f}~ms",
    "s1": lambda v, n: f"{v:.1f}~s",
}
N_REQUIRED = {"pct_kn", "frac", "kn"}


def _plain(tex: str) -> str:
    return tex.replace("\\%", "%").replace("~", " ").replace("$<$", "<")


def render_claims() -> List[Dict[str, str]]:
    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))["macros"]
    cache: Dict[str, Any] = {}
    claims: List[Dict[str, str]] = []
    for name in sorted(spec):
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise SystemExit(f"invalid macro name: {name!r}")
        c = spec[name]
        rel = Path(c["file"])
        if rel.parts[0] != "results":
            raise SystemExit(f"{name}: source {rel.as_posix()} is outside results/")
        if c["file"] not in cache:
            path = REPO_ROOT / rel
            cache[c["file"]] = (json.loads(path.read_text(encoding="utf-8")),
                                hashlib.sha256(path.read_bytes()).hexdigest()[:12])
        doc, sha = cache[c["file"]]
        value = resolve_pointer(doc, c["ptr"])
        fmt = c["fmt"]
        if fmt == "intlist":
            if not isinstance(value, list) or not all(isinstance(x, int) and not isinstance(x, bool) for x in value):
                raise SystemExit(f"{name}: intlist requires a list of integers at {c['file']}#{c['ptr']}")
            tex = ", ".join(str(x) for x in value)
        else:
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise SystemExit(f"{name}: non-numeric leaf at {c['file']}#{c['ptr']}")
            n = None
            if fmt in N_REQUIRED:
                n = resolve_pointer(doc, c["n_ptr"])
            tex = FORMATS[fmt](float(value), n)
        claims.append({"name": name, "tex": tex, "plain": _plain(tex), "fmt": fmt,
                       "src": f"{c['file']}#{c['ptr']}", "sha": sha})
    return claims


def render_tex() -> str:
    lines = [HEADER]
    for c in render_claims():
        lines.append(f"% src: {c['src']} sha256:{c['sha']}")
        lines.append(f"\\newcommand{{\\{c['name']}}}{{{c['tex']}}}")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUT_PATH.write_text(render_tex(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT_PATH.relative_to(REPO_ROOT).as_posix()}")
    return 0


generate_macros = main


if __name__ == "__main__":
    sys.exit(main())
