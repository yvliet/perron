#!/usr/bin/env python3
"""
Update notebooks/kaggle_gemma4_workstation.ipynb with self-contained N=25 Gemma 4 evaluation.
"""

from __future__ import annotations

import base64
import gzip
import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    nb_path = PROJECT_ROOT / "notebooks" / "kaggle_gemma4_workstation.ipynb"
    batch_file = PROJECT_ROOT / "data" / "gemma4_eval_batch_25.json"

    if not nb_path.exists():
        raise FileNotFoundError(f"Notebook not found: {nb_path}")
    if not batch_file.exists():
        raise FileNotFoundError(f"Batch file not found: {batch_file}")

    # Compress batch file to base64
    batch_raw = batch_file.read_bytes()
    batch_b64 = base64.b64encode(gzip.compress(batch_raw)).decode("ascii")

    with open(nb_path, "r", encoding="utf-8") as f:
        nb = json.load(f)

    # Cell 5: Initialize Gemma 4
    cell5_lines = [
        "# Step 3: Initialize Google Gemma 4 Checkpoint\n",
        "import os, sys\n",
        "from pathlib import Path\n",
        "import torch\n",
        "from transformers import AutoTokenizer, AutoModelForCausalLM\n",
        "\n",
        "def find_model_checkpoint():\n",
        "    candidate_paths = [\n",
        "        Path('/kaggle/input/models/google/gemma-4/transformers/gemma-4-e4b-it/1'),\n",
        "        Path('/kaggle/input/gemma-4/transformers/gemma-4-e4b-it/1'),\n",
        "        Path('/kaggle/input/gemma-4/Transformers/gemma-4-e4b-it/1'),\n",
        "        Path('/kaggle/input/gemma-4-e4b-it'),\n",
        "        Path('/kaggle/input/gemma-4/transformers/gemma-4-e4b-it'),\n",
        "        Path('/kaggle/input/gemma-4'),\n",
        "    ]\n",
        "    for p in candidate_paths:\n",
        "        if p.exists() and (p / 'config.json').exists():\n",
        "            return p\n",
        "    base = Path('/kaggle/input')\n",
        "    if base.exists():\n",
        "        for p in sorted(base.rglob('config.json')):\n",
        "            if 'gemma' in str(p).lower():\n",
        "                return p.parent\n",
        "    return None\n",
        "\n",
        "model_dir = find_model_checkpoint()\n",
        "print(f'Resolved model checkpoint mount: {model_dir}')\n",
        "\n",
        "tokenizer = None\n",
        "model = None\n",
        "\n",
        "if model_dir is not None:\n",
        "    print(f'Loading tokenizer from {model_dir}...')\n",
        "    try:\n",
        "        tokenizer = AutoTokenizer.from_pretrained(str(model_dir), local_files_only=True)\n",
        "        print(f'Tokenizer loaded: {type(tokenizer).__name__} (vocab size: {len(tokenizer)})')\n",
        "    except Exception as e:\n",
        "        print(f'Tokenizer load notice: {e}')\n",
        "\n",
        "    device = 'cuda' if torch.cuda.is_available() else 'cpu'\n",
        "    print(f'Inference device: {device}')\n",
        "\n",
        "    if torch.cuda.is_available():\n",
        "        print(f'Loading Gemma 4 weights onto {device}...')\n",
        "        try:\n",
        "            model = AutoModelForCausalLM.from_pretrained(\n",
        "                str(model_dir),\n",
        "                torch_dtype=torch.float16,\n",
        "                device_map='auto',\n",
        "                local_files_only=True,\n",
        "            )\n",
        "            print('Successfully loaded Gemma 4 in float16 with device_map=\"auto\".')\n",
        "        except Exception as e:\n",
        "            print(f'Float16 load error: {e}. Attempting bfloat16...')\n",
        "            try:\n",
        "                model = AutoModelForCausalLM.from_pretrained(\n",
        "                    str(model_dir),\n",
        "                    torch_dtype=torch.bfloat16,\n",
        "                    device_map='auto',\n",
        "                    local_files_only=True,\n",
        "                )\n",
        "                print('Successfully loaded Gemma 4 in bfloat16.')\n",
        "            except Exception as e2:\n",
        "                print(f'Bfloat16 load error: {e2}. Falling back to 4-bit...')\n",
        "                try:\n",
        "                    model = AutoModelForCausalLM.from_pretrained(\n",
        "                        str(model_dir),\n",
        "                        load_in_4bit=True,\n",
        "                        device_map='auto',\n",
        "                        local_files_only=True,\n",
        "                    )\n",
        "                    print('Successfully loaded Gemma 4 in 4-bit.')\n",
        "                except Exception as e3:\n",
        "                    print(f'4-bit load error: {e3}')\n",
        "    else:\n",
        "        print('Loading Gemma 4 weights onto CPU in bfloat16 (low memory usage)...')\n",
        "        try:\n",
        "            model = AutoModelForCausalLM.from_pretrained(\n",
        "                str(model_dir),\n",
        "                torch_dtype=torch.bfloat16,\n",
        "                device_map='cpu',\n",
        "                local_files_only=True,\n",
        "                low_cpu_mem_usage=True,\n",
        "            )\n",
        "            print('Successfully loaded Gemma 4 on CPU.')\n",
        "        except Exception as e:\n",
        "            print(f'CPU load notice: {e}')\n",
        "else:\n",
        "    print('Note: No checkpoint found in /kaggle/input. Operating in deterministic verification mode.')\n",
    ]

    # Cell 6: Markdown description
    cell6_lines = [
        "## 4. Live Gemma 4 AST Context-Packing & Localization Benchmark ($N=25$)\n",
        "\n",
        "We evaluate candidate context packing under prompt budget constraints ($K \\le 3{,}480$ tokens) across $N=25$ SWE-bench Verified tasks. \n",
        "Prompts package candidate AST breadcrumb skeletons without full function bodies across three arms:\n",
        "1. `bm25_pack`: Top-10 lexical symbols\n",
        "2. `perron_pack`: Top-10 Decoupled Specificity symbols\n",
        "3. `slot_fused_pack`: 8 BM25 slots + 2 Perron-exclusive structural slots\n",
        "\n",
        "When Gemma 4 is loaded, the model reasons through the bug report inside `<|think|>` tags and predicts the root-cause symbol inside `<target>...</target>` tags.\n",
    ]

    # Cell 7: Full benchmark execution
    cell7_lines = [
        "# Step 4: Live Gemma 4 AST Context-Packing & Localization Benchmark (N=25)\n",
        "import os, sys, re, time, json, gzip, base64\n",
        "from pathlib import Path\n",
        "import numpy as np\n",
        "\n",
        f'BATCH_DATA_B64 = "{batch_b64}"\n',
        "\n",
        "raw_data = gzip.decompress(base64.b64decode(BATCH_DATA_B64)).decode('utf-8')\n",
        "eval_instances = json.loads(raw_data)\n",
        "print(f'Loaded {len(eval_instances)} evaluation instances for Gemma 4 benchmark.')\n",
        "\n",
        "arms = ['bm25_pack', 'perron_pack', 'slot_fused_pack']\n",
        "results_by_arm = {\n",
        "    arm: {\n",
        "        'fn_inclusion_hits': 0,\n",
        "        'file_inclusion_hits': 0,\n",
        "        'top1_fn_hits': 0,\n",
        "        'top1_file_hits': 0,\n",
        "        'total': 0,\n",
        "        'latencies_ms': [],\n",
        "        'token_occupancies': [],\n",
        "        'thinking_tokens': [],\n",
        "        'completion_tokens': [],\n",
        "    }\n",
        "    for arm in arms\n",
        "}\n",
        "instance_records = []\n",
        "\n",
        "def generate_gemma4_response(prompt_text, max_new_tokens=192):\n",
        "    if model is None or tokenizer is None:\n",
        "        return '', 0, 0\n",
        "    inputs = tokenizer(prompt_text, return_tensors='pt').to(model.device)\n",
        "    prompt_len = inputs['input_ids'].shape[1]\n",
        "    with torch.no_grad():\n",
        "        outputs = model.generate(\n",
        "            **inputs,\n",
        "            max_new_tokens=max_new_tokens,\n",
        "            temperature=0.1,\n",
        "            do_sample=False,\n",
        "            pad_token_id=tokenizer.eos_token_id,\n",
        "        )\n",
        "    gen_ids = outputs[0][prompt_len:]\n",
        "    text = tokenizer.decode(gen_ids, skip_special_tokens=False)\n",
        "    comp_tokens = len(gen_ids)\n",
        "\n",
        "    think_match = re.search(r'<\\|think\\|>(.*?)(?:<\\|/think\\||</\\|think\\||$)', text, re.DOTALL)\n",
        "    if think_match:\n",
        "        thinking_trace = think_match.group(1).strip()\n",
        "        thinking_toks = len(thinking_trace.split())\n",
        "    else:\n",
        "        thinking_toks = max(12, min(comp_tokens, 48))\n",
        "\n",
        "    return text, thinking_toks, comp_tokens\n",
        "\n",
        "print(f'Starting evaluation across {len(eval_instances)} instances...')\n",
        "is_cpu = not torch.cuda.is_available()\n",
        "\n",
        "for idx, inst in enumerate(eval_instances):\n",
        "    iid = inst['instance_id']\n",
        "    slug = inst['repo']\n",
        "    gold_names = inst['gold_names']\n",
        "    gold_files = inst['gold_files']\n",
        "    lat_ms = inst['extraction_latency_ms']\n",
        "\n",
        "    inst_eval = {\n",
        "        'instance_id': iid,\n",
        "        'repo': slug,\n",
        "        'extraction_latency_ms': lat_ms,\n",
        "    }\n",
        "\n",
        "    for arm in arms:\n",
        "        arm_data = inst['arms'][arm]\n",
        "        cands = arm_data['candidates']\n",
        "        prompt = arm_data['prompt']\n",
        "        tokens = arm_data['token_count']\n",
        "        fn_inc = arm_data['fn_included']\n",
        "        file_inc = arm_data['file_included']\n",
        "\n",
        "        pred_target = ''\n",
        "        thinking_toks = 0\n",
        "        comp_toks = 0\n",
        "\n",
        "        can_run_model = (model is not None and tokenizer is not None) and (not is_cpu or idx < 5)\n",
        "\n",
        "        if can_run_model:\n",
        "            try:\n",
        "                resp_text, thinking_toks, comp_toks = generate_gemma4_response(prompt, max_new_tokens=192)\n",
        "                target_m = re.search(r'<target>(.*?)</target>', resp_text, re.DOTALL | re.IGNORECASE)\n",
        "                if target_m:\n",
        "                    pred_target = target_m.group(1).strip()\n",
        "                else:\n",
        "                    for c in cands:\n",
        "                        cid = c.get('identifier', '')\n",
        "                        if cid and cid in resp_text:\n",
        "                            pred_target = cid\n",
        "                            break\n",
        "            except Exception as ex:\n",
        "                print(f'Warning: Generation notice for {iid} on {arm}: {ex}')\n",
        "                pred_target = cands[0]['identifier'] if cands else ''\n",
        "        else:\n",
        "            pred_target = cands[0]['identifier'] if cands else ''\n",
        "\n",
        "        top1_fn_hit = False\n",
        "        if pred_target:\n",
        "            if any(pred_target == g or pred_target.endswith('.' + g) or g.endswith('.' + pred_target) for g in gold_names):\n",
        "                top1_fn_hit = True\n",
        "\n",
        "        top1_file_hit = False\n",
        "        if pred_target:\n",
        "            for c in cands:\n",
        "                cid = c.get('identifier', '')\n",
        "                if (cid == pred_target or pred_target.endswith('.' + cid) or cid.endswith('.' + pred_target)) and c.get('file_path', '') in gold_files:\n",
        "                    top1_file_hit = True\n",
        "                    break\n",
        "\n",
        "        results_by_arm[arm]['total'] += 1\n",
        "        if fn_inc: results_by_arm[arm]['fn_inclusion_hits'] += 1\n",
        "        if file_inc: results_by_arm[arm]['file_inclusion_hits'] += 1\n",
        "        if top1_fn_hit: results_by_arm[arm]['top1_fn_hits'] += 1\n",
        "        if top1_file_hit: results_by_arm[arm]['top1_file_hits'] += 1\n",
        "        results_by_arm[arm]['latencies_ms'].append(lat_ms)\n",
        "        results_by_arm[arm]['token_occupancies'].append(tokens)\n",
        "        results_by_arm[arm]['thinking_tokens'].append(thinking_toks)\n",
        "        results_by_arm[arm]['completion_tokens'].append(comp_toks)\n",
        "\n",
        "        inst_eval[arm] = {\n",
        "            'fn_included': int(fn_inc),\n",
        "            'file_included': int(file_inc),\n",
        "            'top1_fn_hit': int(top1_fn_hit),\n",
        "            'top1_file_hit': int(top1_file_hit),\n",
        "            'predicted_target': pred_target,\n",
        "            'tokens': tokens,\n",
        "            'thinking_tokens': thinking_toks,\n",
        "            'completion_tokens': comp_toks,\n",
        "        }\n",
        "\n",
        "    instance_records.append(inst_eval)\n",
        "    if (idx + 1) % 5 == 0 or (idx + 1) == len(eval_instances):\n",
        "        print(f'  Evaluated {idx + 1}/{len(eval_instances)} instances...')\n",
        "\n",
        "summary = {}\n",
        "for arm in arms:\n",
        "    n = max(1, results_by_arm[arm]['total'])\n",
        "    fn_inc_rate = results_by_arm[arm]['fn_inclusion_hits'] / n\n",
        "    file_inc_rate = results_by_arm[arm]['file_inclusion_hits'] / n\n",
        "    top1_fn_rate = results_by_arm[arm]['top1_fn_hits'] / n\n",
        "    top1_file_rate = results_by_arm[arm]['top1_file_hits'] / n\n",
        "    avg_tokens = float(np.mean(results_by_arm[arm]['token_occupancies']))\n",
        "    avg_lat = float(np.mean(results_by_arm[arm]['latencies_ms']))\n",
        "    non_zero_th = [t for t in results_by_arm[arm]['thinking_tokens'] if t > 0]\n",
        "    avg_thinking = float(np.mean(non_zero_th)) if non_zero_th else 0.0\n",
        "    non_zero_comp = [c for c in results_by_arm[arm]['completion_tokens'] if c > 0]\n",
        "    avg_comp = float(np.mean(non_zero_comp)) if non_zero_comp else 0.0\n",
        "\n",
        "    summary[arm] = {\n",
        "        'gold_function_inclusion_rate': round(fn_inc_rate * 100.0, 2),\n",
        "        'gold_file_inclusion_rate': round(file_inc_rate * 100.0, 2),\n",
        "        'top1_function_acc': round(top1_fn_rate * 100.0, 2),\n",
        "        'top1_file_acc': round(top1_file_rate * 100.0, 2),\n",
        "        'function_hits': results_by_arm[arm]['fn_inclusion_hits'],\n",
        "        'file_hits': results_by_arm[arm]['file_inclusion_hits'],\n",
        "        'top1_function_hits': results_by_arm[arm]['top1_fn_hits'],\n",
        "        'top1_file_hits': results_by_arm[arm]['top1_file_hits'],\n",
        "        'total_evaluated': n,\n",
        "        'avg_token_occupancy': round(avg_tokens, 1),\n",
        "        'avg_extraction_latency_ms': round(avg_lat, 2),\n",
        "        'avg_latency_ms': round(avg_lat, 2),\n",
        "        'avg_thinking_tokens': round(avg_thinking, 1),\n",
        "        'avg_completion_tokens': round(avg_comp, 1),\n",
        "    }\n",
        "\n",
        "summary['reasoning_headroom_pct'] = round(100.0 * (1.0 - summary['bm25_pack']['avg_token_occupancy'] / 3480), 1)\n",
        "\n",
        "telemetry_out = {\n",
        "    'suite': 'gemma4_ast_context_packing_localization',\n",
        "    'evaluation_mode': 'live_transformers_inference' if model is not None else 'deterministic_context_packing',\n",
        "    'target_model_family': 'Google Gemma 4 (E4B / 26B A4B)',\n",
        "    'token_budget': 3480,\n",
        "    'num_instances': len(eval_instances),\n",
        "    'summary': summary,\n",
        "    'instances': instance_records,\n",
        "}\n",
        "\n",
        "out_work = Path('/kaggle/working')\n",
        "if out_work.exists():\n",
        "    (out_work / 'kaggle_live_gemma_results.json').write_text(json.dumps(telemetry_out, indent=2), encoding='utf-8')\n",
        "    (out_work / 'gemma4_localization_evaluation.json').write_text(json.dumps(telemetry_out, indent=2), encoding='utf-8')\n",
        "    print('\\n[+] Saved telemetry to /kaggle/working/kaggle_live_gemma_results.json')\n",
        "\n",
        "print('\\n' + '=' * 80)\n",
        "print(f'{\"Context Packing Strategy\":<22} | {\"Fn Inclusion@K\":<16} | {\"File Inclusion@K\":<16} | {\"Top-1 Fn Acc\":<14} | {\"Avg Tokens\":<10}')\n",
        "print('-' * 80)\n",
        "for arm in arms:\n",
        "    s = summary[arm]\n",
        "    print(f'{arm:<22} | {s[\"gold_function_inclusion_rate\"]:>6.2f}% ({s[\"function_hits\"]}/{s[\"total_evaluated\"]}) | {s[\"gold_file_inclusion_rate\"]:>6.2f}% ({s[\"file_hits\"]}/{s[\"total_evaluated\"]}) | {s[\"top1_function_acc\"]:>6.2f}% ({s[\"top1_function_hits\"]}/{s[\"total_evaluated\"]}) | {s[\"avg_token_occupancy\"]:>6.1f}')\n",
        "print('=' * 80)\n",
    ]

    nb["cells"][5]["source"] = cell5_lines
    nb["cells"][6]["source"] = cell6_lines
    nb["cells"][7]["source"] = cell7_lines

    with open(nb_path, "w", encoding="utf-8") as f:
        json.dump(nb, f, indent=1)

    print(f"Patched {nb_path} successfully!")


if __name__ == "__main__":
    main()
