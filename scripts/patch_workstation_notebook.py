        "## 4. AST Context-Budgeted Breadcrumb Packing Benchmark ($N=344$)\n",
        "\n",
        "We evaluate candidate context packing under prompt budget constraints ($K \\le 3{,}480$ tokens) across all $N=344$ callable SWE-bench Verified tasks. \n",
